import streamlit as st

# כותרת ראשית מעוצבת ומקצועית
st.title("🤖 מערכת תפעול ואופטימיזציה: מסעדה חכמה")
st.subheader("מערכת תומכת החלטה (DSS) לניהול ולוגיסטיקה של צי רובוטים אוטונומיים")

st.divider()

# --- חלק 1: אודות המערכת והקשר הנדסי ---
st.subheader("💡 אודות המערכת והקשר הנדסי-מציאותי")

st.write("""
במסגרת ניהול הלוגיסטיקה ותפעול הרשת של המסעדה החכמה, המערכת מיישמת כלי חקר ביצועים 
ומודלים מתמטיים מתקדמים כדי למזער עלויות תפעול ורכש, תוך שמירה על רמת שירות הרמטית ומהירה.

המערכת מחולקת לשלושה צירי אופטימיזציה מרכזיים, המאפשרים ניתוח דינמי לחלוטין מבוסס קבצי נתונים (Excel):
""")

# תצוגת שלושת המודלים בתוך עמודות מעוצבות עם תיעוד קצר
m_col1, m_col2, m_col3 = st.columns(3)

with m_col1:
    st.info("""
    ### 📍 מיקום וכיסוי (Set Cover)
    קביעת כמות המינימום של רובוטים הנדרשים לשירות וחלוקת אזורי העבודה במסעדה, תוך שימוש ב-**Greedy Heuristic** ושבירת תיקו הנדסית.
    """)

with m_col2:
    st.info("""
    ### ⚡ ניווט דינמי (Dijkstra)
    חישוב מסלולי הנסיעה הקצרים ביותר בזמן אמת מקודקוד המקור (המטבח) אל שולחנות הסועדים ועמדות הטעינה, למניעת עיכובים והתקררות המנות.
    """)

with m_col3:
    st.info("""
    ### 🌊 זרימה מקסימלית (Max Flow)
    ניתוח וסימולציה של תזרים ההזמנות ברשת מהמטבח ועד השולחנות, תוך זיהוי אוטומטי של **צווארי בקבוק** והתמודדות עם השבתות רובוטים.
    """)

st.divider()

# --- חלק 2: הוראות הפעלה למשתמש ---
st.subheader("🚀 כיצד להשתמש במערכת?")
st.write("""
1. השתמשי ב**תפריט הניווט הצידי** כדי לעבור בין מודלי האופטימיזציה השונים.
2. בכל עמוד, תוכלי להעלות קובץ אקסל (`.xlsx`) מותאם אישית עם מבנה הנתונים של המסעדה שלך.
3. המערכת תריץ את האלגוריתמים המתמטיים בצורה אוטומטית לחלוטין ותציג פלט גרפי ותפעולי מעודכן בזמן אמת!
""")

st.divider()
st.caption("⚙️ פותח במסגרת פרויקט גמר - אופטימיזציה ומערכות מידע לוגיסטיות.")
